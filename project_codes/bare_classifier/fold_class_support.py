"""
fold_class_support.py
=====================

Shows, concretely, how many instances of each class land in each TEST fold,
for K=5 vs K=10 and for the 4-class vs a merged 3-class target. This is the
empirical version of the "is K=10 too thin / should classes merge?" question:
it lets you SEE the rare-class support per fold instead of reasoning about it.

It rebuilds y exactly as the pipeline does (revonsets.max() per ccode, with
revonsets>2 -> 3), so the counts match training reality. If you can't point it
at the data, pass the class counts directly (see CONFIG / --counts).

Usage:
    python fold_class_support.py                 # uses dv_augm.h5 if available
    python fold_class_support.py --counts 27 57 30 16 7 15 7 4 4 8 5 2
        # (not needed; for offline use it can synthesize a y from total counts)

Reads only labels; no model, no training.
"""

import argparse
import os
import numpy as np
import pandas as pd
from sklearn.model_selection import StratifiedKFold


DV_PATH = "../../project_data/dv_augm.h5"
OUT_DIR = "../../project_results/tsai_no_tda_Results/fold_support_out/"


# ---------------------------------------------------------------------------
def load_y_from_data():
    """Rebuild the per-country label exactly as the pipeline does."""
    dv = pd.read_hdf(DV_PATH, key="data").sort_values(["ccode", "year"])
    dv["revonsets_category"] = dv["revonsets"]
    dv.loc[dv["revonsets"] > 2, "revonsets_category"] = 3
    dv["revonsets"] = dv["revonsets_category"].astype(int)
    dv = dv.drop(columns=["revonsets_category"])
    ccodes = dv["ccode"].unique().tolist()
    y = np.array([dv.loc[dv["ccode"] == c, "revonsets"].max() for c in ccodes])
    return y


def synth_y_from_totals(totals):
    """Build a y vector from total per-class counts (order = class 0,1,2,3)."""
    y = np.concatenate([np.full(n, k) for k, n in enumerate(totals)])
    return y


# ---------------------------------------------------------------------------
def fold_support_table(y, n_splits, label, detail_rows, summary_rows):
    classes = sorted(np.unique(y).tolist())
    skf = StratifiedKFold(n_splits=n_splits, shuffle=True, random_state=42)
    print(f"\n=== {label}: K={n_splits}, classes={classes}, N={len(y)} ===")
    print(f"total per class: " +
          ", ".join(f"c{c}={int((y==c).sum())}" for c in classes))
    header = "fold | " + " | ".join(f"c{c}" for c in classes) + " | test_n | min_class"
    print(header); print("-" * len(header))
    min_per_fold = []
    for k, (_, te) in enumerate(skf.split(np.zeros(len(y)), y)):
        counts = [int((y[te] == c).sum()) for c in classes]
        mn = min(counts)
        min_per_fold.append(mn)
        print(f"  {k}  | " + " | ".join(f"{n:2d}" for n in counts) +
              f" |  {len(te):3d}  |   {mn}")
        row = {"config": label, "n_splits": n_splits, "fold": k,
               "test_n": int(len(te)), "min_class_support": mn}
        for c in classes:
            row[f"class_{c}"] = int((y[te] == c).sum())
        detail_rows.append(row)
    worst = min(min_per_fold)
    print(f"worst-case rarest-class test support across folds: {worst}")
    if worst >= 5:
        verdict = "OK (>=5 per fold: per-class metrics reasonably stable)"
    elif worst >= 3:
        verdict = "THIN (3-4: per-class metrics noisy, usable with caveat)"
    else:
        verdict = "FRAGILE (<3: per-class metrics unstable; avoid)"
    print(f"verdict: {verdict}")
    summary_rows.append({
        "config": label, "n_classes": len(classes), "n_splits": n_splits,
        "N": int(len(y)),
        "total_per_class": "/".join(str(int((y == c).sum())) for c in classes),
        "worst_rare_class_support": int(worst),
        "mean_test_n": int(round(np.mean([
            r["test_n"] for r in detail_rows
            if r["config"] == label and r["n_splits"] == n_splits]))),
        "verdict": verdict.split(" (")[0],
    })
    return worst


def merge_to_3class(y):
    """Collapse classes 2 and 3 into a single '2+' class (0,1,2)."""
    y3 = y.copy()
    y3[y3 == 3] = 2
    return y3


def export(detail_rows, summary_rows):
    os.makedirs(OUT_DIR, exist_ok=True)
    detail = pd.DataFrame(detail_rows)
    summary = pd.DataFrame(summary_rows)
    dp = os.path.join(OUT_DIR, "fold_support_detail.csv")
    sp = os.path.join(OUT_DIR, "fold_support_summary.csv")
    detail.to_csv(dp, index=False)
    summary.to_csv(sp, index=False)
    print(f"\nsaved {dp}\nsaved {sp}")

    # LaTeX: the summary is the table you'd put in an appendix
    def esc(s): return str(s).replace("_", r"\_").replace("%", r"\%")
    L = [r"% Auto-generated by fold_class_support.py",
         r"\begin{table}[htbp]", r"\centering", r"\small",
         r"\caption{Per-fold class support under stratified $K$-fold "
         r"cross-validation, for the 4-class and merged 3-class targets at "
         r"$K=5$ and $K=10$. \emph{Worst rare-class support} is the smallest "
         r"number of minority-class instances in any single test fold; values "
         r"below about 5 make per-class metrics unstable.}",
         r"\label{tab:fold_support}",
         r"\begin{tabular}{lrrrrl}", r"\toprule",
         r"Configuration & classes & $K$ & total/class & worst rare & verdict \\",
         r"\midrule"]
    for _, r in summary.iterrows():
        L.append(f"{esc(r['config'])} & {int(r['n_classes'])} & "
                 f"{int(r['n_splits'])} & {esc(r['total_per_class'])} & "
                 f"{int(r['worst_rare_class_support'])} & {esc(r['verdict'])} \\\\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    tp = os.path.join(OUT_DIR, "fold_support_summary.tex")
    with open(tp, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"saved {tp}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--counts", nargs="+", type=int, default=None,
                    help="optional total per-class counts (class 0..3) to "
                         "synthesize y offline, e.g. --counts 38 80 42 22")
    args = ap.parse_args()

    if args.counts:
        y = synth_y_from_totals(args.counts)
        print(f"[using synthesized y from totals {args.counts}]")
    else:
        try:
            y = load_y_from_data()
            print("[loaded y from dv_augm.h5]")
        except Exception as e:
            print(f"[could not load data: {e}]")
            print("Falling back to totals from your reported single split "
                  "(27+7+4, 57+15+8, 30+7+5, 16+4+2):")
            y = synth_y_from_totals([38, 80, 42, 22])

    detail_rows, summary_rows = [], []

    print("\n############ 4-CLASS TARGET (0,1,2,3) ############")
    fold_support_table(y, 5, "4-class", detail_rows, summary_rows)
    fold_support_table(y, 10, "4-class", detail_rows, summary_rows)

    print("\n############ MERGED 3-CLASS TARGET (0,1,2+) ############")
    y3 = merge_to_3class(y)
    fold_support_table(y3, 5, "3-class (2 and 3 merged)", detail_rows, summary_rows)
    fold_support_table(y3, 10, "3-class (2 and 3 merged)", detail_rows, summary_rows)

    export(detail_rows, summary_rows)

    print("""
HOW TO READ THIS
  - 'worst-case rarest-class test support' is the key number: the fewest
    instances of the rarest class in any single test fold.
  - >=5 is reasonably stable; 3-4 is usable-with-caveat; <3 is fragile.
  - Compare K=5 vs K=10 (K=10 roughly halves the support) and 4-class vs
    3-class (merging roughly doubles the rare-class support).
  - Pick the (K, target) combination whose worst-case support clears ~5 while
    keeping test folds large enough overall.
  - CSV (detail + summary) and a LaTeX summary table are written to OUT_DIR
    for the appendix.
""")


if __name__ == "__main__":
    main()
