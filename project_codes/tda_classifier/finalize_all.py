"""
finalize_all.py
===============

Run the CV finalize step (figures + metrics) across ALL backbones at once,
instead of invoking finalize_cv_figures.py per folder.

It auto-discovers every "backbone folder" under a root: a directory that
contains fold_0/, fold_1/, ... subfolders. For each, it calls finalize().

    python finalize_all.py  /path/to/epochs_900   [n_classes]

Example root layout it expects:
    epochs_900/
        RNNAttention_val_0.2_test_0.1/
            fold_0/ fold_predictions.npz ...
            fold_1/ ...
            cv_final/            <- created
        LSTMAttention_val_0.2_test_0.1/
            fold_0/ ...
        ...

For each backbone it reports whether fold_predictions.npz files are present.
If they are not, it says so and skips that backbone.

No training. This only reads saved per-fold predictions.
"""

import os
import sys
import glob
import numpy as np
import pandas as pd

from classification_python_codes.finalize_cv_figures import finalize


def discover_backbone_folders(root):
    """A backbone folder is any dir containing at least one fold_*/ subdir."""
    found = set()
    for fold_dir in glob.glob(os.path.join(root, "**", "fold_*"), recursive=True):
        if os.path.isdir(fold_dir):
            found.add(os.path.dirname(fold_dir))
    return sorted(found)


def has_predictions(backbone_folder):
    return len(glob.glob(os.path.join(backbone_folder, "fold_*",
                                      "fold_predictions.npz"))) > 0


def _clean_name(folder):
    """Backbone name from folder, dropping the _val_..._test_... suffix."""
    base = os.path.basename(folder.rstrip("/"))
    for marker in ("_val_", "_val", "-val_"):
        if marker in base:
            return base.split(marker)[0]
    return base


def aggregate_summaries(root, backbone_folders, n_classes):
    """Stack every backbone's pooled-OOF + CV-mean metrics into ONE table,
    written to `root` (the dir you passed, which contains the epochs_900 tree).
    Reads the per-backbone CSVs that finalize() already wrote."""
    rows = []
    for bb in backbone_folders:
        cvdir = os.path.join(bb, "cv_final")
        spath = os.path.join(cvdir, "metrics_cv_summary.csv")
        ppath = os.path.join(cvdir, "metrics_pooled_oof.csv")
        if not (os.path.exists(spath) and os.path.exists(ppath)):
            continue
        s = pd.read_csv(spath).iloc[0].to_dict()
        p = pd.read_csv(ppath).iloc[0].to_dict()
        row = {
            "backbone": _clean_name(bb),
            # CV mean +/- sd (across folds)
            "acc_cv_mean": s.get("accuracy_mean"), "acc_cv_sd": s.get("accuracy_std"),
            "kappa_cv_mean": s.get("qw_kappa_mean"), "kappa_cv_sd": s.get("qw_kappa_std"),
            "macroauc_cv_mean": s.get("macro_auc_mean"), "macroauc_cv_sd": s.get("macro_auc_std"),
            # pooled out-of-fold (stable headline; each country once)
            "acc_pooled": p.get("accuracy"),
            "kappa_pooled": p.get("qw_kappa"),
            "macroauc_pooled": p.get("macro_auc"),
        }
        for c in range(n_classes):
            row[f"auc_c{c}_pooled"] = p.get(f"auc_c{c}")
            row[f"support_c{c}"] = p.get(f"support_c{c}")
        rows.append(row)

    if not rows:
        print("[aggregate] no per-backbone summaries found to combine.")
        return

    df = pd.DataFrame(rows).sort_values("macroauc_pooled", ascending=False)
    csv_path = os.path.join(root, "all_backbones_cv_summary.csv")
    df.to_csv(csv_path, index=False)

    # LaTeX: compact comparison table (pooled headline + CV-sd in parens)
    def esc(s): return str(s).replace("_", r"\_")
    L = [r"% Auto-generated by finalize_all.py (aggregate_summaries)",
         r"\begin{table}[htbp]", r"\centering", r"\small",
         r"\caption{Cross-validated performance by backbone. Accuracy, "
         r"quadratic-weighted $\kappa$, and macro AUC are pooled out-of-fold "
         r"(each country held out exactly once); the value in parentheses is "
         r"the across-fold standard deviation. $\kappa$ credits ordinally-close "
         r"predictions on the four-degree belligerency scale.}",
         r"\label{tab:all_backbones}",
         r"\begin{tabular}{lccc}", r"\toprule",
         r"Backbone & Accuracy & QW-$\kappa$ & Macro AUC \\", r"\midrule"]
    for _, r in df.iterrows():
        L.append(
            f"{esc(r['backbone'])} & "
            f"{r['acc_pooled']:.3f} ({r['acc_cv_sd']:.3f}) & "
            f"{r['kappa_pooled']:.3f} ({r['kappa_cv_sd']:.3f}) & "
            f"{r['macroauc_pooled']:.3f} ({r['macroauc_cv_sd']:.3f}) \\\\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    tex_path = os.path.join(root, "all_backbones_cv_summary.tex")
    with open(tex_path, "w") as fh:
        fh.write("\n".join(L) + "\n")

    print(f"\n[aggregate] combined {len(df)} backbones ->")
    print(f"  {csv_path}")
    print(f"  {tex_path}")


def main(root, n_classes=4):

    backbones = discover_backbone_folders(root)
    if not backbones:
        print(f"No backbone folders (containing fold_*/) found under {root}")
        sys.exit(1)

    print(f"Found {len(backbones)} backbone folder(s) under {root}\n")
    done, skipped = [], []
    for bb in backbones:
        name = os.path.basename(bb.rstrip("/"))
        if not has_predictions(bb):
            n_folds = len(glob.glob(os.path.join(bb, "fold_*")))
            print(f"[SKIP] {name}: {n_folds} fold(s) but no fold_predictions.npz "
                  f"(SAVE_PREDS was not active during this run).")
            skipped.append(name)
            continue
        print(f"[RUN ] {name}")
        try:
            finalize(bb, n_classes=n_classes)
            done.append(name)
        except Exception as e:
            print(f"[ERR ] {name}: {e}")
            skipped.append(name)
        print()

    print("=" * 60)
    print(f"finalized: {len(done)}  | skipped: {len(skipped)}")
    if done:    print("  done:    " + ", ".join(done))
    if skipped: print("  skipped: " + ", ".join(skipped))

    # combine all finalized backbones' summaries into one table at `root`
    finalized_folders = [bb for bb in backbones
                         if os.path.exists(os.path.join(bb, "cv_final", "metrics_pooled_oof.csv"))]
    aggregate_summaries(root, finalized_folders, n_classes)

    if skipped:
        print("\nFor skipped backbones (no .npz): either re-run those backbones "
              "with the SAVE_PREDS edit active, OR generate predictions post-hoc "
              "from each fold's saved model .pkl (inference only, no training) -- "
              "see the post-hoc predict script.")


if __name__ == "__main__":
    root = "../../project_results/tsai_yes_tda_gpd_Results/classification_models/epochs_900"
    n_classes = int(sys.argv[2]) if len(sys.argv) > 2 else 4
    main(root, n_classes)
